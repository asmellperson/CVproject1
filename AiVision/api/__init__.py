"""
api/：AiVision 的 HTTP 接口入口

这个目录把前端请求转换为配置服务或运行对象的调用，负责应用组装、认证入口、
依赖注入和 HTTP 错误表达。摄像头采集、模型推理和检测状态由各业务模块管理。
本文件只作讲解；应用对象在 app.py 中创建，检测生命周期由 Orchestrator 管理。

一、每个文件负责什么

    app.py：create_app() 创建 FastAPI，配置 CORS、认证中间件、异常处理器，
        挂载 auth.api 及 routes/ 的路由；模块级 app 也由此函数创建。
        认证结果保存在 request.state.user，供后续依赖读取。
        未处理异常写日志，并按系统异常通知配置和冷却条件发送企业微信通知。
    deps.py：把共享配置服务和运行对象提供给路由。
        get_current_orchestrator() 在编排器尚未初始化时返回 HTTP 503。
        get_optional_orchestrator() 允许不依赖运行状态的配置接口继续工作。
        获取已有管理器不等于创建另一套摄像头、Worker 或后台线程。
    server.py：退出时关闭 AGV 请求入口，等待 HTTP 响应和后台回调结束，
        主入口随后再清理模型、采集和共享管理器。
    routes/：按摄像头、检测功能、模型、告警、通道等业务拆分 endpoint。
        子目录的 __init__.py 列出具体路由文件及职责。

二、一次请求怎么走

    浏览器 / 调用方 → FastAPI 中间件 → 身份认证 → 路由依赖与参数校验
        → 资源归属和功能权限检查 → service / Orchestrator → HTTP 响应。
    OPTIONS、登录、退出、运行健康检查和 /api/public/ 路径不走普通认证拦截。
    public 路由仍需执行自身约定的校验，例如通知缩略图的签名验证。
    已登录只代表身份有效；管理员权限、事业部归属和功能分配还要分别检查。

三、和其他模块怎么联系

    ../main.py 调用 create_app() 后交给 Uvicorn 监听；API 不自行启动模型。
    ../../auth/ 提供登录、用户管理和权限依赖。
    ../features/、../cameras/、../departments/ 等提供配置和业务服务。
    ../runtime/ 提供运行状态、监控帧和整体启停；../alarms/ 提供记录和媒体。
    前端 src/lib/ 和业务组件中的 API 封装消费这里的接口契约。

四、如果我要增加或修改接口

    优先在对应 routes 文件中扩展，复用现有 Schema、service 和权限依赖。
    新建路由文件后要在 app.py 显式挂载，只放进目录不会自动成为 HTTP 接口。
    需要数据库提交或运行热更新时，沿用所属服务的事务和通知流程。
    修改响应字段前检查前端调用方，避免接口返回与 TypeScript 类型不一致。

五、修改后怎么验证

    检查路由挂载、请求校验、未登录/无权限响应、正常读写和资源不存在的情况。
    配置接口还要核对数据库提交后的运行状态；仅改本说明无需启动 HTTP 服务。
"""
