"""
AiVision/：视觉平台的业务后端

这个目录把摄像头采集、模型推理、检测规则、告警证据和 HTTP API 组织在一起。
前端通过 API 配置和查看结果；实时检测由后端的进程、线程和队列持续运行。
本文件只作讲解，导入 AiVision 不会在这里启动服务、连接摄像头或加载模型。

一、先分清几个角色

    Camera：提供视频帧，同一摄像头的画面可以被多个检测功能使用。
    Model Worker：执行模型推理，输出检测框、关键点或特征匹配结果。
    Feature / Consumer：声明并执行业务规则，决定检测结果意味着什么。
    Runtime：管理资源生命周期，或汇总通道、保安室等多摄像头业务状态。
    Alarm：接收业务告警，协调记录、截图、录像、喇叭和企业微信。
    API：处理请求、认证授权和参数校验，把实际工作交给服务或运行对象。

二、每个目录负责什么

    main.py：正式启动入口，加载环境配置、准备数据库、创建 Orchestrator，
        启动检测和 Uvicorn，并在退出时回收资源。
    api/：FastAPI 应用、依赖注入和按业务拆分的 routes/。
    runtime/：数据库 bootstrap、整体启停、配置事件处理和总览快照。
    cameras/：摄像头配置、采集子进程、共享内存和最新帧读取。
    inference/：固定模型注册表、本机权重路径、推理队列和 Worker 进程。
    features/：各检测功能的 spec、配置、Consumer 及专属业务服务。
        registry.py 显式汇总功能，_shared/ 提供公共检测框架。
    alarms/：统一分发、设备通信、消息通知、告警记录和视频证据。
    departments/：固定事业部目录，以及数据库中的事业部功能分配。
    connectors/：海康人员接口、JoyAI Adapter 等外部系统通信。
    core/：环境配置、数据库、日志、配置缓存、事件和媒体公共能力。
    config/：本机模型路径的配置示例；真实路径由部署环境维护。
    migrations/：需要显式执行的离线数据迁移，不在包导入时运行。

三、和仓库其他模块怎么联系

    ../auth/：认证、用户、事业部功能权限和访问审计，路由由本后端挂载。
        auth 与业务数据使用同一套数据库基础设施。
    ../unified_frontend/：React 页面通过 /api 读取配置、运行状态和证据。
        页面 ID、Python 包名和 FeatureSpec.name 不一定相同，不能相互替代。

四、一张图片与一次配置保存的流程

    摄像头 → CameraRuntime → 共享内存 → FrameReader → Consumer
        → 模型队列 → Worker → 结果队列 → 业务判定 → 告警和监控状态。
    不依赖模型的门状态检测直接处理图像；AGV 检测等待 HTTP 请求再采样。
    物流通道和保安室先接收各摄像头快照，再由各自 Runtime 汇总判断。

    前端配置 → API 权限与 Schema 校验 → 所属服务提交数据库
        → 对应缓存刷新或运行通知 → Consumer / Runtime 使用新配置。
    模型文件路径由 inference/model_paths.py 保存到 YAML，走独立的重载流程。

五、如果我要修改或增加功能

    先从 features/registry.py 找到功能声明，再读对应目录的 __init__.py。
    规则放 Consumer 或专属状态模块；外部协议放 connector；HTTP 处理放 routes。
    新功能需要同时检查注册表、ORM/Schema、模型依赖、权限和前端业务标识。
    数据库结构变化要提供相应迁移，bootstrap 不会自动修补已有表。

六、修改后怎么验证

    先检查受影响模块的 Python 语法，再验证对应规则、配置保存和 API 权限。
    涉及实时链路时，检查启动、停止、热更新和故障恢复；真实摄像头、权重及
    外部服务需在具备相应资源的环境验证。仅修改包说明时检查语法和 Git 差异，
    并比较去除模块文档字符串后的 AST，确认可执行语句没有改变。
"""
