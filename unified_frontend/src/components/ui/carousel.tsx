const CarouselContext = React.createContext<CarouselContextProps | null>(null)

/**
 * 功能：封装 `useCarousel` React Hook，向调用组件提供`carousel` 模块状态与操作
 * 参数：无。
 * 返回：未显式标注（由 TypeScript 推断）；返回实现中 `return` 表达式计算得到的结果。
 * 调用关系：
 *   - 调用方：`unified_frontend/src/components/ui/carousel.tsx` 的 `CarouselContent`
 *         调用本符号；`unified_frontend/src/components/ui/carousel.tsx` 的 `CarouselItem`
 *         调用本符号；`unified_frontend/src/components/ui/carousel.tsx` 的 `CarouselPrevious`
 *         调用本符号；`unified_frontend/src/components/ui/carousel.tsx` 的 `CarouselNext` 调用本符号
 *   - 内部调用：`useContext`、`Error`、`Carousel`。
 * 副作用/注意事项：校验或请求失败时会主动抛出异常。
 */
function useCarousel() {
  const context = React.useContext(CarouselContext)

  if (!context) {
    throw new Error("useCarousel must be used within a <Carousel />")
  }

  return context
}

/**
 * 功能：渲染 `Carousel` React 组件，根据输入属性组织界面并返回 JSX 节点
 * 参数：
 *   - `props`（React.ComponentProps<"div"> & CarouselProps）：React 组件属性对象；解构字段包括 orientation, horizontal, opts, setApi, plugins,
 *     className, children, props
 * 返回：JSX.Element（由 React 推断）；返回用于界面渲染的 React 元素树。
 * 调用关系：
 *   - 调用方：`unified_frontend/src/components/ui/carousel.tsx` 的 `useCarousel` 调用本符号
 *   - 内部调用：`useEmblaCarousel`、`useState`、`useCallback`、`setCanScrollPrev`、`canScrollPrev`、`setCanScrollNext`、`canScrollNext`、`scrollPrev`、`scrollNext`、`preventDefault`
 *          等共 19 个调用。
 * 副作用/注意事项：会更新 React 状态并触发相关组件重新渲染。
 */
function Carousel({
  orientation = "horizontal",
  opts,
  setApi,
  plugins,
  className,
  children,
  ...props
}: React.ComponentProps<"div"> & CarouselProps) {
  const [carouselRef, api] = useEmblaCarousel(
    {
      ...opts,
      axis: orientation === "horizontal" ? "x" : "y",
    },
    plugins
  )
  const [canScrollPrev, setCanScrollPrev] = React.useState(false)
  const [canScrollNext, setCanScrollNext] = React.useState(false)

  const onSelect = React.useCallback((api: CarouselApi) => {
    if (!api) return
    setCanScrollPrev(api.canScrollPrev())
    setCanScrollNext(api.canScrollNext())
  }, [])

  const scrollPrev = React.useCallback(() => {
    api?.scrollPrev()
  }, [api])

  const scrollNext = React.useCallback(() => {
    api?.scrollNext()
  }, [api])

  const handleKeyDown = React.useCallback(
    (event: React.KeyboardEvent<HTMLDivElement>) => {
      if (event.key === "ArrowLeft") {
        event.preventDefault()
        scrollPrev()
      } else if (event.key === "ArrowRight") {
        event.preventDefault()
        scrollNext()
      }
    },
    [scrollPrev, scrollNext]
  )

  React.useEffect(() => {
    if (!api || !setApi) return
    setApi(api)
  }, [api, setApi])

  React.useEffect(() => {
    if (!api) return
    onSelect(api)
    api.on("reInit", onSelect)
    api.on("select", onSelect)

    return () => {
      api?.off("select", onSelect)
    }
  }, [api, onSelect])

  return (
    <CarouselContext.Provider
      value={{
        carouselRef,
        api: api,
        opts,
        orientation:
          orientation || (opts?.axis === "y" ? "vertical" : "horizontal"),
        scrollPrev,
        scrollNext,
        canScrollPrev,
        canScrollNext,
      }}
    >
      <div
        onKeyDownCapture={handleKeyDown}
        className={cn("relative", className)}
        role="region"
        aria-roledescription="carousel"
        data-slot="carousel"
        {...props}
      >
        {children}
      </div>
    </CarouselContext.Provider>
  )
}

